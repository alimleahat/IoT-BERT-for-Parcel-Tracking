def generate_dataset():
    """Generate train/test split from intent templates."""
    train_data = []
    test_data = []

    for intent, samples in INTENTS.items():
        random.shuffle(samples)
        # 80/20 split
        split_idx = max(int(len(samples) * 0.8), 1)
        train_samples = samples[:split_idx]
        test_samples = samples[split_idx:]

        for text in train_samples:
            train_data.append({"text": text, "label": intent})
        for text in test_samples:
            test_data.append({"text": text, "label": intent})

    random.shuffle(train_data)
    random.shuffle(test_data)

    return train_data, test_data


if __name__ == "__main__":
    train_data, test_data = generate_dataset()

    os.makedirs("data", exist_ok=True)
    with open("data/train.json", "w") as f:
        json.dump(train_data, f, indent=2)
    with open("data/test.json", "w") as f:
        json.dump(test_data, f, indent=2)

    print(f"Training samples: {len(train_data)}")
    print(f"Test samples:     {len(test_data)}")
    print("\nPer-intent breakdown:")
    for intent in INTENTS:
        tr = sum(1 for d in train_data if d["label"] == intent)
        te = sum(1 for d in test_data if d["label"] == intent)
        print(f"  {intent:20s}  train={tr:3d}  test={te:3d}")
